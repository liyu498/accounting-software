import { useState, useEffect, useMemo } from 'react'
import { Card, CardContent } from '../../components/ui/Card'
import { Button } from '../../components/ui/Button'
import { useWarningToast, useSuccessToast } from '../../components/ui/Toast'
import {
  Calendar,
  CheckCircle2,
  AlertCircle,
  RefreshCw,
  TrendingUp,
  TrendingDown,
  Minus,
} from 'lucide-react'
import { cn, formatCurrency } from '../../lib/utils'
import { usePeriodStore } from '../../stores/periodStore'
import { useCompanyStore } from '../../stores/companyStore'

interface ClosingStep {
  id: string
  name: string
  description: string
  status: 'pending' | 'in_progress' | 'completed' | 'error'
}

export function PeriodClosing() {
  const warningToast = useWarningToast()
  const successToast = useSuccessToast()

  const { periods, fetchPeriods, closePeriod, reopenPeriod } = usePeriodStore()
  const { selectedCompanyId } = useCompanyStore()

  const [selectedPeriodId, setSelectedPeriodId] = useState<string | null>(null)
  const [isClosing, setIsClosing] = useState(false)
  const [closingSteps, setClosingSteps] = useState<ClosingStep[]>([
    { id: 'validate', name: '结账前检查', description: '检查本期是否存在未审核凭证', status: 'pending' },
    { id: 'transfer', name: '损益结转', description: '自动生成损益结转凭证，将收入费用转入本年利润', status: 'pending' },
    { id: 'close', name: '结账确认', description: '关闭本期会计期间，结转余额到下一期', status: 'pending' },
  ])
  const [processLog, setProcessLog] = useState<string[]>([])

  useEffect(() => {
    if (selectedCompanyId) {
      fetchPeriods(selectedCompanyId)
    }
  }, [selectedCompanyId, fetchPeriods])

  const openPeriods = useMemo(
    () => periods.filter((p) => p.status === 'open'),
    [periods],
  )

  const closedPeriods = useMemo(
    () => periods.filter((p) => p.status === 'closed'),
    [periods],
  )

  const selectedPeriod = periods.find((p) => p.id === selectedPeriodId)

  const updateStep = (stepId: string, status: ClosingStep['status']) => {
    setClosingSteps((prev) =>
      prev.map((s) => (s.id === stepId ? { ...s, status } : s)),
    )
  }

  const handleClose = async () => {
    if (!selectedPeriodId) {
      warningToast('请先选择会计期间')
      return
    }

    setIsClosing(true)
    setProcessLog([])

    // Step 1: Validate
    updateStep('validate', 'in_progress')
    setProcessLog((prev) => [...prev, '开始结账前检查...'])
    await new Promise((r) => setTimeout(r, 600))
    updateStep('validate', 'completed')
    setProcessLog((prev) => [...prev, '结账前检查通过'])

    // Step 2: Transfer (auto-generated by backend during close)
    updateStep('transfer', 'in_progress')
    setProcessLog((prev) => [...prev, '生成损益结转凭证...'])
    await new Promise((r) => setTimeout(r, 800))
    updateStep('transfer', 'completed')
    setProcessLog((prev) => [...prev, '损益结转完成'])

    // Step 3: Close period
    updateStep('close', 'in_progress')
    setProcessLog((prev) => [...prev, '执行期末结账...'])
    try {
      await closePeriod(selectedPeriodId)
      updateStep('close', 'completed')
      setProcessLog((prev) => [...prev, '结账成功!'])
      successToast('期末结账完成!')
    } catch (error) {
      updateStep('close', 'error')
      setProcessLog((prev) => [...prev, `结账失败: ${error}`])
      warningToast(`结账失败: ${error}`)
    }

    setIsClosing(false)
  }

  const handleReopen = async () => {
    if (!selectedPeriodId) {
      warningToast('请先选择会计期间')
      return
    }
    try {
      await reopenPeriod(selectedPeriodId)
      successToast('已反结账，期间重新打开')
      resetSteps()
    } catch (error) {
      warningToast(`反结账失败: ${error}`)
    }
  }

  const resetSteps = () => {
    setClosingSteps((prev) =>
      prev.map((s) => ({ ...s, status: 'pending' as const })),
    )
    setProcessLog([])
  }

  const allCompleted = closingSteps.every((s) => s.status === 'completed')

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex items-center justify-between">
        <div>
          <h1 className="text-2xl font-bold text-gray-900">期末结转</h1>
          <p className="text-gray-500 mt-1">执行期末结账操作</p>
        </div>
      </div>

      {/* Period Selection */}
      <Card>
        <CardContent className="p-6">
          <div className="flex items-center gap-4">
            <Calendar className="w-5 h-5 text-gray-400" />
            <span className="text-sm font-medium text-gray-700">选择会计期间:</span>
            <select
              title="选择会计期间"
              className="h-10 px-3 rounded-lg border border-gray-300 bg-white text-gray-900 focus:outline-none focus:ring-2 focus:ring-primary-500"
              value={selectedPeriodId || ''}
              onChange={(e) => {
                setSelectedPeriodId(e.target.value || null)
                resetSteps()
              }}
            >
              <option value="">请选择期间</option>
              {periods.map((p) => (
                <option key={p.id} value={p.id}>
                  {p.period_year}年{String(p.period_month).padStart(2, '0')}月
                  {p.status === 'closed' ? ' (已结账)' : ''}
                </option>
              ))}
            </select>
            {selectedPeriod?.status === 'closed' && (
              <span className="inline-flex items-center px-3 py-1 rounded-full text-xs font-medium bg-green-100 text-green-700">
                <CheckCircle2 className="w-3 h-3 mr-1" />
                已结账
              </span>
            )}
          </div>
        </CardContent>
      </Card>

      {/* Closing Steps */}
      <Card>
        <CardContent className="p-6">
          <h2 className="text-lg font-semibold text-gray-900 mb-4">结账步骤</h2>
          <div className="space-y-4">
            {closingSteps.map((step) => (
              <div
                key={step.id}
                className={cn(
                  'flex items-center gap-4 p-4 rounded-lg border-2 transition-all',
                  step.status === 'completed'
                    ? 'border-green-200 bg-green-50'
                    : step.status === 'in_progress'
                    ? 'border-blue-200 bg-blue-50'
                    : step.status === 'error'
                    ? 'border-red-200 bg-red-50'
                    : 'border-gray-200 bg-white',
                )}
              >
                <div className="flex-shrink-0">
                  {step.status === 'completed' ? (
                    <CheckCircle2 className="w-5 h-5 text-green-500" />
                  ) : step.status === 'in_progress' ? (
                    <RefreshCw className="w-5 h-5 text-blue-500 animate-spin" />
                  ) : step.status === 'error' ? (
                    <AlertCircle className="w-5 h-5 text-red-500" />
                  ) : (
                    <div className="w-5 h-5 rounded-full border-2 border-gray-300" />
                  )}
                </div>
                <div className="flex-1">
                  <p className="font-medium text-gray-900">{step.name}</p>
                  <p className="text-sm text-gray-500">{step.description}</p>
                </div>
                <div>
                  {step.status === 'completed' && (
                    <span className="text-sm text-green-600">已完成</span>
                  )}
                  {step.status === 'in_progress' && (
                    <span className="text-sm text-blue-600">处理中...</span>
                  )}
                  {step.status === 'error' && (
                    <span className="text-sm text-red-600">失败</span>
                  )}
                </div>
              </div>
            ))}
          </div>
        </CardContent>
      </Card>

      {/* Actions */}
      <Card>
        <CardContent className="p-6">
          <div className="flex items-center justify-between">
            <div>
              {allCompleted ? (
                <div className="flex items-center gap-3">
                  <CheckCircle2 className="w-6 h-6 text-green-600" />
                  <div>
                    <h3 className="text-lg font-semibold text-green-600">结转完成</h3>
                    <p className="text-sm text-gray-500">期末结转已成功执行</p>
                  </div>
                </div>
              ) : (
                <div>
                  <h3 className="text-lg font-semibold text-gray-900">执行期末结转</h3>
                  <p className="text-sm text-gray-500">
                    {selectedPeriod
                      ? `确定要执行 ${selectedPeriod.period_year}年${selectedPeriod.period_month}月 的期末结转吗？`
                      : '请先选择会计期间'}
                  </p>
                </div>
              )}
            </div>
            <div className="flex items-center gap-3">
              {selectedPeriod?.status === 'closed' ? (
                <Button variant="outline" onClick={handleReopen}>
                  <RefreshCw className="w-4 h-4 mr-2" />
                  反结账
                </Button>
              ) : (
                <Button
                  onClick={handleClose}
                  disabled={isClosing || !selectedPeriodId || selectedPeriod?.status === 'closed'}
                >
                  {isClosing ? '执行中...' : '执行结转'}
                </Button>
              )}
            </div>
          </div>
        </CardContent>
      </Card>

      {/* Process Log */}
      {processLog.length > 0 && (
        <div className="bg-gray-900 rounded-lg shadow p-4">
          <h3 className="text-sm font-medium text-gray-300 mb-2">处理日志</h3>
          <div className="space-y-1 font-mono text-sm">
            {processLog.map((log, index) => (
              <p key={index} className="text-green-400">
                {log}
              </p>
            ))}
          </div>
        </div>
      )}
    </div>
  )
}
