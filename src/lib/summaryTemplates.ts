export function getSummaryTemplates(accountCode: string): string[] {
  // Try exact match first
  if (summaryTemplateMap[accountCode]) {
    return summaryTemplateMap[accountCode]
  }
  // Try prefix match (e.g., "100201" matches "1002")
  for (let i = accountCode.length; i >= 2; i--) {
    const prefix = accountCode.slice(0, i)
    if (summaryTemplateMap[prefix]) {
      return summaryTemplateMap[prefix]
    }
  }
  return []
}

export function getDefaultSummary(accountCode: string): string {
  const templates = getSummaryTemplates(accountCode)
  return templates.length > 0 ? templates[0] : ''
}
